/** Micro-season for a UTC date: { kanji, romaji, english }. */
export function kouFor(date = new Date()) {
  const mmdd = (date.getUTCMonth() + 1) * 100 + date.getUTCDate();
  let best = null;
  for (const k of KOU) if (k[0] <= mmdd && (!best || k[0] > best[0])) best = k;
  return { kanji: best[1], romaji: best[2], english: best[3] };
}
